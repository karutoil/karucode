//! `karucode plugin init` / `karucode plugin sdk`: scaffolding for plugins.
//!
//! A generated plugin does not depend on karucode at all. The SDK and the wire
//! types are copied into the project (`src/sdk.rs`, `src/protocol.rs`) by
//! [`kc_plugin_sdk::files`], so it builds in any directory, offline, with only
//! `serde` and `serde_json` from crates.io — no path into a karucode checkout and
//! no dependency on a crate being published.
//!
//! That coupling is deliberate and cheap to keep: the host and a plugin only
//! share the JSON-RPC wire protocol, so a vendored copy that was generated by
//! this build is guaranteed to speak what this build speaks.
//! [`sync`] rewrites the vendored modules after a karucode upgrade, and
//! `--check` reports drift so a plugin's CI can fail on a stale copy.

use anyhow::{anyhow, bail, Context};

/// Version a freshly scaffolded plugin starts at (the plugin's own version, not
/// the protocol version).
pub const DEFAULT_PLUGIN_VERSION: &str = "0.1.0";

/// `karucode plugin init <dir> [--name <name>] [--force]`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PluginInitArgs {
    pub dir: std::path::PathBuf,
    pub name: Option<String>,
    pub force: bool,
}

/// `karucode plugin sdk <dir> [--check]`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PluginSdkArgs {
    pub dir: std::path::PathBuf,
    pub check: bool,
}

/// Scaffold a plugin project. Writes nothing unless every file can be generated
/// and none of them already exists (unless `--force`).
pub fn init(args: &PluginInitArgs) -> anyhow::Result<()> {
    let target = &args.dir;
    let name = match &args.name {
        Some(name) => name.clone(),
        None => kc_plugin_sdk::name_from_path(target),
    };
    // Generate first: a name or SDK-emission failure must not leave a
    // half-created directory behind.
    let files = kc_plugin_sdk::files(&name, DEFAULT_PLUGIN_VERSION).map_err(|e| anyhow!("{e}"))?;

    if target.exists() && !target.is_dir() {
        bail!(
            "{} exists and is not a directory; pick another target",
            target.display()
        );
    }
    let existing: Vec<&str> = files
        .iter()
        .map(|(path, _)| path.as_str())
        .filter(|path| target.join(path).exists())
        .collect();
    if !existing.is_empty() && !args.force {
        bail!(
            "refusing to overwrite {} in {}; pass --force to replace them",
            existing.join(", "),
            target.display()
        );
    }

    for (path, content) in &files {
        let full = target.join(path);
        if let Some(parent) = full.parent() {
            std::fs::create_dir_all(parent)
                .with_context(|| format!("could not create {}", parent.display()))?;
        }
        std::fs::write(&full, content)
            .with_context(|| format!("could not write {}", full.display()))?;
    }

    let absolute = std::fs::canonicalize(target).unwrap_or_else(|_| target.clone());
    let binary = absolute.join("target").join("release").join(&name);
    println!(
        "Created plugin `{name}` ({}) in {}\n\n\
         Next steps:\n  \
         cd {} && cargo build --release\n  \
         # add this to ~/.config/karucode/config.toml (or to\n  \
         # <data_dir>/plugins/{name}/plugin.toml):\n\n\
         [[plugins]]\n\
         name = \"{name}\"\n\
         command = [\"{}\"]\n\
         enabled = true\n\n\
         Then check `GET /api/plugins` and call `plugin__{name}__echo`.\n\
         Talk to it without the server:  cd {} && cargo run --quiet\n\
         After upgrading karucode, refresh the vendored SDK:  karucode plugin sdk {}",
        format_args!(
            "plugin protocol {}",
            kc_core::plugin::PLUGIN_PROTOCOL_VERSION
        ),
        absolute.display(),
        absolute.display(),
        binary.display(),
        absolute.display(),
        absolute.display(),
    );
    Ok(())
}

/// Rewrite the vendored SDK/protocol modules from this build, or with `--check`
/// only report whether they are current.
pub fn sync(args: &PluginSdkArgs) -> anyhow::Result<()> {
    let target = &args.dir;
    let files = [
        ("src/protocol.rs", kc_plugin_sdk::protocol_source()),
        (
            "src/sdk.rs",
            kc_plugin_sdk::sdk_source().map_err(|e| anyhow!("{e}"))?,
        ),
    ];

    if args.check {
        let mut stale: Vec<String> = Vec::new();
        for (path, expected) in &files {
            match std::fs::read_to_string(target.join(path)) {
                Ok(current) if current == *expected => {}
                Ok(_) => stale.push(format!("{path} differs")),
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                    stale.push(format!("{path} is missing"))
                }
                Err(e) => {
                    return Err(e)
                        .with_context(|| format!("could not read {path} in {}", target.display()))
                }
            }
        }
        if !stale.is_empty() {
            bail!(
                "the vendored SDK in {} is out of date ({}); run `karucode plugin sdk {}`",
                target.display(),
                stale.join(", "),
                target.display()
            );
        }
        println!(
            "Vendored SDK in {} matches this karucode build (plugin protocol {})",
            target.display(),
            kc_core::plugin::PLUGIN_PROTOCOL_VERSION
        );
        return Ok(());
    }

    for (path, content) in &files {
        let full = target.join(path);
        if let Some(parent) = full.parent() {
            std::fs::create_dir_all(parent)
                .with_context(|| format!("could not create {}", parent.display()))?;
        }
        std::fs::write(&full, content)
            .with_context(|| format!("could not write {}", full.display()))?;
    }
    println!(
        "Refreshed src/protocol.rs and src/sdk.rs in {} to plugin protocol {}",
        target.display(),
        kc_core::plugin::PLUGIN_PROTOCOL_VERSION
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::{Path, PathBuf};

    fn temp_dir(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "karucode-scaffold-{tag}-{}-{:?}",
            std::process::id(),
            std::thread::current().id()
        ));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn init_args(dir: &Path, name: Option<&str>, force: bool) -> PluginInitArgs {
        PluginInitArgs {
            dir: dir.to_path_buf(),
            name: name.map(|n| n.to_string()),
            force,
        }
    }

    #[test]
    fn init_writes_a_buildable_project() {
        let root = temp_dir("init");
        let dir = root.join("wordy");
        init(&init_args(&dir, None, false)).unwrap();

        for path in ["Cargo.toml", "src/main.rs", "src/protocol.rs", "src/sdk.rs"] {
            assert!(dir.join(path).is_file(), "{path} was not written");
        }
        let manifest = std::fs::read_to_string(dir.join("Cargo.toml")).unwrap();
        assert!(manifest.contains("name = \"wordy\""));
        assert!(!manifest.contains("kc-plugin-sdk"));
        // The vendored SDK must be the one this build ships.
        let sdk = std::fs::read_to_string(dir.join("src/sdk.rs")).unwrap();
        assert!(sdk.contains("pub use crate::protocol::*;"));
        let protocol = std::fs::read_to_string(dir.join("src/protocol.rs")).unwrap();
        assert!(protocol.contains(kc_core::plugin::PLUGIN_PROTOCOL_VERSION));
        std::fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn init_honours_an_explicit_name() {
        let root = temp_dir("explicit-name");
        let dir = root.join("whatever");
        init(&init_args(&dir, Some("my-plugin"), false)).unwrap();
        let manifest = std::fs::read_to_string(dir.join("Cargo.toml")).unwrap();
        assert!(manifest.contains("name = \"my-plugin\""));
        std::fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn init_refuses_to_clobber_without_force() {
        let root = temp_dir("clobber");
        let dir = root.join("wordy");
        init(&init_args(&dir, None, false)).unwrap();
        std::fs::write(dir.join("src/main.rs"), "// mine\n").unwrap();

        let err = init(&init_args(&dir, None, false)).unwrap_err().to_string();
        assert!(err.contains("--force"), "{err}");
        assert_eq!(
            std::fs::read_to_string(dir.join("src/main.rs")).unwrap(),
            "// mine\n",
            "a refused init must not touch existing files"
        );

        init(&init_args(&dir, None, true)).unwrap();
        assert!(std::fs::read_to_string(dir.join("src/main.rs"))
            .unwrap()
            .contains("PluginBuilder"));
        std::fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn init_rejects_an_invalid_name_before_writing_anything() {
        let root = temp_dir("bad-name");
        let dir = root.join("wordy");
        let err = init(&init_args(&dir, Some("../evil"), false))
            .unwrap_err()
            .to_string();
        assert!(err.contains("invalid plugin name"), "{err}");
        assert!(!dir.exists(), "nothing may be created for a rejected name");
        std::fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn init_rejects_a_file_as_target() {
        let root = temp_dir("file-target");
        let target = root.join("not-a-dir");
        std::fs::write(&target, "x").unwrap();
        let err = init(&init_args(&target, None, false))
            .unwrap_err()
            .to_string();
        assert!(err.contains("not a directory"), "{err}");
        std::fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn sdk_check_reports_drift_and_sync_repairs_it() {
        let root = temp_dir("sync");
        let dir = root.join("wordy");
        init(&init_args(&dir, None, false)).unwrap();

        // Fresh scaffold is current.
        sync(&PluginSdkArgs {
            dir: dir.clone(),
            check: true,
        })
        .unwrap();

        // An edited vendored copy is stale.
        std::fs::write(dir.join("src/sdk.rs"), "// local hack\n").unwrap();
        let err = sync(&PluginSdkArgs {
            dir: dir.clone(),
            check: true,
        })
        .unwrap_err()
        .to_string();
        assert!(err.contains("out of date"), "{err}");
        assert!(err.contains("src/sdk.rs"), "{err}");

        // …and sync repairs it, and never touches the user's own sources.
        std::fs::write(dir.join("src/main.rs"), "// mine\n").unwrap();
        sync(&PluginSdkArgs {
            dir: dir.clone(),
            check: false,
        })
        .unwrap();
        sync(&PluginSdkArgs {
            dir: dir.clone(),
            check: true,
        })
        .unwrap();
        assert_eq!(
            std::fs::read_to_string(dir.join("src/main.rs")).unwrap(),
            "// mine\n"
        );
        std::fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn sdk_check_reports_missing_modules() {
        let root = temp_dir("sync-missing");
        let dir = root.join("empty");
        std::fs::create_dir_all(&dir).unwrap();
        let err = sync(&PluginSdkArgs {
            dir: dir.clone(),
            check: true,
        })
        .unwrap_err()
        .to_string();
        assert!(err.contains("is missing"), "{err}");
        std::fs::remove_dir_all(&root).ok();
    }
}
