//! Emission of a dependency-free copy of this SDK into a scaffolded plugin.
//!
//! `karucode plugin init <dir>` writes the files [`files`] returns: a
//! `Cargo.toml`, a starter `src/main.rs`, and the two vendored modules
//! `src/protocol.rs` (the wire types from [`kc_core::plugin`]) and `src/sdk.rs`
//! (this crate's own body). The generated plugin depends on nothing but `serde`
//! and `serde_json` — there is no path into a karucode checkout and no reliance
//! on a crate published to a registry.
//!
//! # Why a copy beats a dependency here
//!
//! The host and the plugin are only coupled by the wire protocol, so the SDK is
//! convenience, not an ABI: a plugin written in Python needs none of this. A
//! vendored copy keeps that property — it builds offline, in any directory, with
//! no version solving against the harness's dependency tree.
//!
//! # Keeping the copy honest
//!
//! There is one copy of the code, not two. `sdk.rs` is cut out of this crate's
//! own `lib.rs` at [`SDK_SOURCE_MARKER`], and `protocol.rs` is
//! [`kc_core::PLUGIN_PROTOCOL_SOURCE`]; both are `include_str!`ed at build time,
//! so a plugin generated by karucode *N* speaks exactly what karucode *N* speaks.
//! [`sdk_source`] refuses to emit anything if the marker or the `kc_core::plugin`
//! re-export disappeared, so a future refactor of this crate fails loudly instead
//! of shipping a plugin that does not compile.
//!
//! The emitted `sdk.rs` carries no `@kc-doc` metadata: the block lives above the
//! marker precisely so a generated plugin created inside a karucode checkout
//! cannot introduce a duplicate doc slug.

use std::fmt;

/// Marks the start of the part of `lib.rs` that is copied into a plugin.
///
/// Everything below it must compile with only `serde` and `serde_json`, and must
/// refer to the wire types as `kc_core::plugin` (rewritten to `crate::protocol`
/// on the way out).
pub const SDK_SOURCE_MARKER: &str = "// ---- BEGIN EMBEDDED SDK SOURCE ----";

/// Placeholder replaced by the plugin name in the templates.
const NAME: &str = "__PLUGIN_NAME__";
/// Placeholder replaced by the plugin version in the templates.
const VERSION: &str = "__PLUGIN_VERSION__";

const SDK_LIB_SOURCE: &str = include_str!("lib.rs");

/// Why a scaffold could not be generated.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EmbedError {
    /// [`SDK_SOURCE_MARKER`] is gone from `lib.rs`: the SDK body can no longer be
    /// cut out. Restore the marker rather than removing this check.
    MarkerMissing,
    /// The SDK body no longer re-exports the wire types, so the rewrite to
    /// `crate::protocol` would produce a plugin that does not compile.
    ProtocolPathMissing,
    /// The name is not usable as both a Cargo package name and a plugin name.
    InvalidName(&'static str),
}

impl fmt::Display for EmbedError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::MarkerMissing => write!(
                f,
                "this karucode build cannot emit a plugin SDK: `{}` is missing from \
                 kc-plugin-sdk/src/lib.rs",
                SDK_SOURCE_MARKER
            ),
            Self::ProtocolPathMissing => write!(
                f,
                "this karucode build cannot emit a plugin SDK: kc-plugin-sdk/src/lib.rs no longer \
                 re-exports `kc_core::plugin`"
            ),
            Self::InvalidName(reason) => write!(f, "invalid plugin name: {reason}"),
        }
    }
}

impl std::error::Error for EmbedError {}

/// Check that `name` works as a Cargo package name, a binary name and a plugin
/// manifest name. Lowercase keeps it identical in all three places.
pub fn validate_name(name: &str) -> Result<(), EmbedError> {
    if name.is_empty() {
        return Err(EmbedError::InvalidName("it is empty"));
    }
    let mut chars = name.chars();
    let first = chars.next().expect("checked non-empty");
    if !first.is_ascii_lowercase() {
        return Err(EmbedError::InvalidName(
            "it must start with a lowercase ASCII letter",
        ));
    }
    if !name
        .chars()
        .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-' || c == '_')
    {
        return Err(EmbedError::InvalidName(
            "it may contain only lowercase ASCII letters, digits, `-` and `_`",
        ));
    }
    Ok(())
}

/// Derive a plugin name from a directory name (`my-plugin`, `my-plugin-2`, …).
///
/// Non-alphanumeric characters become `-`, ASCII uppercase is lowered, and a
/// leading non-letter is prefixed with `plugin-` so the result is a legal crate
/// name.
pub fn name_from_path(path: &std::path::Path) -> String {
    let raw = path
        .file_name()
        .map(|n| n.to_string_lossy().to_string())
        .unwrap_or_default();
    let mut out: String = raw
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect();
    while out.contains("--") {
        out = out.replace("--", "-");
    }
    let out = out.trim_matches('-').to_string();
    if out.is_empty() {
        return "plugin".to_string();
    }
    match out.chars().next() {
        Some(c) if c.is_ascii_lowercase() => out,
        _ => format!("plugin-{out}"),
    }
}

/// The SDK body that is copied into a plugin as `src/sdk.rs`.
///
/// Cuts `lib.rs` at [`SDK_SOURCE_MARKER`], rewrites `kc_core::plugin` to the
/// plugin's own `crate::protocol` module and prepends a provenance header.
pub fn sdk_source() -> Result<String, EmbedError> {
    let (_, body) = SDK_LIB_SOURCE
        .split_once(SDK_SOURCE_MARKER)
        .ok_or(EmbedError::MarkerMissing)?;
    if !body.contains("pub use kc_core::plugin::*;") {
        return Err(EmbedError::ProtocolPathMissing);
    }
    let body = body
        .replace("kc_core::plugin", "crate::protocol")
        .trim_start_matches('\n')
        .to_string();
    Ok(with_header(&body))
}

/// The wire types that are copied into a plugin as `src/protocol.rs`.
pub fn protocol_source() -> String {
    with_header(kc_core::PLUGIN_PROTOCOL_SOURCE)
}

/// Prepend the "generated, do not edit" header, after any inner `//!` module
/// docs so the result stays a legal module file.
fn with_header(source: &str) -> String {
    let header = format!(
        "// Generated by `karucode plugin init` (plugin protocol version {}).\n\
         // Do not edit by hand: this is a copy of the SDK that build ships.\n\
         // Refresh it after upgrading karucode with `karucode plugin sdk .`",
        kc_core::plugin::PLUGIN_PROTOCOL_VERSION
    );
    let mut out = String::with_capacity(source.len() + header.len() + 2);
    let mut written = false;
    for line in source.lines() {
        if !written && !line.trim_start().starts_with("//!") {
            out.push_str(&header);
            out.push_str("\n\n");
            written = true;
        }
        out.push_str(line);
        out.push('\n');
    }
    if !written {
        out.push_str(&header);
        out.push('\n');
    }
    out
}

/// Every file `karucode plugin init` writes, as `(relative path, contents)`.
///
/// The order is stable: manifest, entry point, vendored protocol, vendored SDK.
pub fn files(name: &str, version: &str) -> Result<Vec<(String, String)>, EmbedError> {
    validate_name(name)?;
    Ok(vec![
        ("Cargo.toml".to_string(), manifest(name, version)),
        ("src/main.rs".to_string(), entry_point(name, version)),
        ("src/protocol.rs".to_string(), protocol_source()),
        ("src/sdk.rs".to_string(), sdk_source()?),
    ])
}

fn manifest(name: &str, version: &str) -> String {
    MANIFEST_TEMPLATE
        .replace(NAME, name)
        .replace(VERSION, version)
}

fn entry_point(name: &str, version: &str) -> String {
    ENTRY_POINT_TEMPLATE
        .replace(NAME, name)
        .replace(VERSION, version)
}

const MANIFEST_TEMPLATE: &str = r#"[package]
name = "__PLUGIN_NAME__"
version = "__PLUGIN_VERSION__"
edition = "2021"

[[bin]]
name = "__PLUGIN_NAME__"
path = "src/main.rs"

# The SDK is vendored in src/sdk.rs and src/protocol.rs, so the only dependencies
# are serde (wire types) and serde_json (request/response plumbing). Nothing here
# points into a karucode checkout or at a published karucode crate.
[dependencies]
serde = { version = "1", features = ["derive"] }
serde_json = "1"
"#;

const ENTRY_POINT_TEMPLATE: &str = r#"//! `__PLUGIN_NAME__` — a karucode plugin.
//!
//! A plugin is a plain process: it reads one JSON-RPC request per line on stdin
//! and writes one response per line on stdout. Nothing else may go to stdout;
//! logs belong on stderr. The protocol plumbing lives in the vendored modules
//! `src/sdk.rs` and `src/protocol.rs` — refresh both with `karucode plugin sdk .`
//! after upgrading karucode.
//!
//! Debug it without the server:
//!
//! ```bash
//! printf '%s\n' \
//!   '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocol":"1"}}' \
//!   '{"jsonrpc":"2.0","id":2,"method":"tools/list","params":{}}' \
//!   | cargo run --quiet
//! ```

// The vendored modules expose more API than this starter uses; without these
// allowances every unused protocol type would warn on the first build.
#[allow(dead_code)]
mod protocol;
#[allow(dead_code)]
mod sdk;

use sdk::{PluginBuilder, PluginToolResult, PluginToolResultExt, ToolRequest};
use serde_json::json;

fn main() -> std::io::Result<()> {
    PluginBuilder::new("__PLUGIN_NAME__", "__PLUGIN_VERSION__")
        .description("TODO: one line about what this plugin does")
        // .permission(sdk::permissions::FILES_READ)  // declare what it touches
        .tool(
            "echo",
            "Echo the given text back.",
            json!({
                "type": "object",
                "properties": { "text": { "type": "string", "description": "Text to echo." } },
                "required": ["text"]
            }),
            |req: ToolRequest| {
                let text = req.str_arg("text");
                if text.is_empty() {
                    return PluginToolResult::err("`text` is required");
                }
                PluginToolResult::ok(text)
            },
        )
        // .hook(sdk::hooks::BEFORE_PROMPT, |_payload| json!("note for the system prompt"))
        .run()
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_marker_and_the_protocol_reexport_are_present() {
        // Guards the two things `sdk_source` rewrites; if this fails, the
        // scaffold would emit a plugin that does not compile.
        assert!(SDK_LIB_SOURCE.contains(SDK_SOURCE_MARKER));
        assert!(SDK_LIB_SOURCE.contains("pub use kc_core::plugin::*;"));
    }

    #[test]
    fn the_emitted_sdk_is_a_self_contained_module() {
        let sdk = sdk_source().unwrap();
        assert!(sdk.contains("pub use crate::protocol::*;"));
        assert!(!sdk.contains("kc_core"), "no harness crate may leak in");
        assert!(sdk.contains("pub struct PluginBuilder"));
        assert!(sdk.contains("PluginToolResultExt"));
        // The doc block must not travel: a plugin generated inside a karucode
        // checkout would otherwise duplicate the `plugins` slug.
        assert!(!sdk.contains("@kc-doc"));
        assert!(!sdk.contains("@kc-applies-to"));
    }

    /// The emitted copy has to keep working for the panel and context paths, not
    /// just for tools: a generated plugin is the only place a plugin author ever
    /// reads this API, so a rewrite that dropped it would be invisible until
    /// their build failed.
    #[test]
    fn the_emitted_sdk_carries_the_panel_and_context_api() {
        let sdk = sdk_source().unwrap();
        for needle in [
            "pub struct PanelRequest",
            "pub struct ToolRequest",
            "pub fn panel(",
            "pub fn panel_with(",
            "pub fn context(&self)",
            "pub fn workspace(&self)",
            "pub fn session_id(&self)",
            "methods::PANELS_READ",
            "PANEL_SOURCE_STATIC",
        ] {
            assert!(
                sdk.contains(needle),
                "the emitted SDK is missing `{needle}`"
            );
        }
        // The wire types it refers to are re-exported from the sibling module,
        // which is what the `kc_core::plugin` -> `crate::protocol` rewrite
        // assumes.
        let protocol = protocol_source();
        for needle in [
            "pub struct PluginPanel",
            "pub struct PluginPanelData",
            "pub struct ToolCallContext",
            "pub const PANELS_READ",
        ] {
            assert!(
                protocol.contains(needle),
                "the emitted protocol is missing `{needle}`"
            );
        }
    }

    /// A scaffolded plugin that says nothing about panels must keep scaffolding
    /// exactly as before: the starter `main.rs` is unchanged and declares none.
    #[test]
    fn the_scaffolded_entry_point_declares_no_panels() {
        let files = files("wordy", "0.1.0").unwrap();
        let main = &files[1].1;
        assert!(!main.contains(".panel("));
        // But the vendored SDK it compiles against does.
        let sdk = &files[3].1;
        assert!(sdk.contains("pub fn panel("));
    }

    #[test]
    fn the_emitted_protocol_keeps_its_module_docs_and_gets_a_header() {
        let protocol = protocol_source();
        assert!(protocol.starts_with("//! "), "inner docs must stay first");
        assert!(protocol.contains("// Generated by `karucode plugin init`"));
        assert!(protocol.contains("pub const PLUGIN_PROTOCOL_VERSION"));
        assert!(protocol.contains("pub struct PluginManifest"));
        // The provenance header has to sit after the `//!` block, not before it.
        let header_at = protocol.find("// Generated by").unwrap();
        let first_item = protocol.find("use serde::").unwrap();
        assert!(header_at < first_item);
    }

    #[test]
    fn generated_files_are_named_after_the_plugin() {
        let files = files("wordy", "0.2.1").unwrap();
        let paths: Vec<&str> = files.iter().map(|(p, _)| p.as_str()).collect();
        assert_eq!(
            paths,
            ["Cargo.toml", "src/main.rs", "src/protocol.rs", "src/sdk.rs"]
        );
        let manifest = &files[0].1;
        assert!(manifest.contains("name = \"wordy\""));
        assert!(manifest.contains("version = \"0.2.1\""));
        assert!(!manifest.contains(NAME));
        let main = &files[1].1;
        assert!(main.contains("PluginBuilder::new(\"wordy\", \"0.2.1\")"));
        assert!(!main.contains(NAME));
        assert!(!main.contains(VERSION));
        // No path dependency, in any shape.
        let deps = manifest.split("[dependencies]").nth(1).unwrap();
        assert!(!deps.contains("path"));
        assert!(!deps.contains("kc-plugin-sdk"));
        assert!(!deps.contains("git"));
    }

    #[test]
    fn names_are_validated_before_anything_is_written() {
        assert!(validate_name("wordy-2").is_ok());
        assert!(validate_name("wordy_2").is_ok());
        assert_eq!(
            validate_name(""),
            Err(EmbedError::InvalidName("it is empty"))
        );
        assert!(matches!(
            validate_name("Wordy"),
            Err(EmbedError::InvalidName(_))
        ));
        assert!(matches!(
            validate_name("2wordy"),
            Err(EmbedError::InvalidName(_))
        ));
        assert!(matches!(
            validate_name("wordy/evil"),
            Err(EmbedError::InvalidName(_))
        ));
        assert!(files("../evil", "0.1.0").is_err());
    }

    #[test]
    fn names_are_derived_from_the_directory() {
        use std::path::Path;
        assert_eq!(name_from_path(Path::new("/tmp/wordy")), "wordy");
        assert_eq!(name_from_path(Path::new("/tmp/My Plugin")), "my-plugin");
        assert_eq!(name_from_path(Path::new("/tmp/my--plugin")), "my-plugin");
        assert_eq!(name_from_path(Path::new("/tmp/2fast")), "plugin-2fast");
        assert_eq!(name_from_path(Path::new("/")), "plugin");
    }

    #[test]
    fn embed_errors_explain_the_repair() {
        for error in [
            EmbedError::MarkerMissing,
            EmbedError::ProtocolPathMissing,
            EmbedError::InvalidName("it is empty"),
        ] {
            assert!(!error.to_string().is_empty());
        }
    }
}
