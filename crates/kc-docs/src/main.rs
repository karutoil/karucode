//! `kc-docs` — regenerate or verify the human-readable copy of karucode's
//! internal documentation.
//!
//! The binary *embeds* its docs at compile time, so this tool is about the files
//! under `docs/internal/`: they exist for review, for editors and for people who
//! do not want to start the server. `--check` is the CI gate that keeps them in
//! sync with the code.

use kc_docs::parse::{self, ParsedDoc};
use kc_docs::scan;
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

const GENERATED_MARKER: &str = "<!-- @generated by `cargo run -p kc-docs -- --write`";

struct Args {
    command: Command,
    root: PathBuf,
    out: PathBuf,
}

enum Command {
    Check,
    Write,
    List,
    Read(String),
    Search(String),
}

fn usage() -> &'static str {
    "kc-docs — karucode internal documentation compiler

Usage: kc-docs [COMMAND] [OPTIONS]

Commands (a leading `--` is accepted, e.g. `--write`):
  check               Verify docs/internal matches the code (default)
  write               Regenerate docs/internal from @kc-doc blocks
  list                Print every topic: slug, title, source
  read <slug>         Print one topic as markdown
  search <query...>   Print ranked search results for a query

Options:
  --root <DIR>   Workspace root (default: the checkout this binary was built from)
  --out <DIR>    Output directory (default: <root>/docs/internal)
  -h, --help     Print this help

The embedded copy the agent reads is compiled by build.rs on every cargo build;
these files are the committed, reviewable mirror.
"
}

/// Map a command word to its command. `read`/`search` take the rest of the
/// command line as their argument, signalled by the `None` payload.
fn command_for(word: &str) -> Option<Option<Command>> {
    match word {
        "check" => Some(Some(Command::Check)),
        "write" => Some(Some(Command::Write)),
        "list" => Some(Some(Command::List)),
        "read" => Some(None),
        "search" => Some(None),
        _ => None,
    }
}

fn main() -> ExitCode {
    let args = match parse_args(std::env::args().skip(1)) {
        Ok(Some(args)) => args,
        Ok(None) => {
            print!("{}", usage());
            return ExitCode::SUCCESS;
        }
        Err(message) => {
            eprintln!("kc-docs: {message}\n\n{}", usage());
            return ExitCode::from(2);
        }
    };

    match args.command {
        Command::Check => check(&args),
        Command::Write => write(&args),
        Command::List => {
            for doc in kc_docs::all() {
                println!("{:<24} {:<60} {}", doc.slug, doc.title, doc.source);
            }
            println!("\n{} topic(s)", kc_docs::count());
            quality_gate()
        }
        Command::Read(slug) => match kc_docs::render_doc(&slug) {
            Some(text) => {
                println!("{text}");
                ExitCode::SUCCESS
            }
            None => {
                eprintln!(
                    "kc-docs: no topic `{slug}`. Known topics: {}",
                    kc_docs::slugs().join(", ")
                );
                ExitCode::FAILURE
            }
        },
        Command::Search(query) => {
            let hits = kc_docs::search(&query, 10);
            print!("{}", kc_docs::render_hits(&query, &hits));
            if hits.is_empty() {
                ExitCode::FAILURE
            } else {
                ExitCode::SUCCESS
            }
        }
    }
}

fn parse_args<I>(args: I) -> Result<Option<Args>, String>
where
    I: IntoIterator<Item = String>,
{
    let mut command: Option<Command> = None;
    let mut root: Option<PathBuf> = None;
    let mut out: Option<PathBuf> = None;

    let args: Vec<String> = args.into_iter().collect();
    let mut i = 0;
    while i < args.len() {
        let arg = &args[i];
        let word = arg.strip_prefix("--").unwrap_or(arg.as_str());
        match word {
            "h" | "help" => return Ok(None),
            "root" | "out" => {
                let value = args
                    .get(i + 1)
                    .ok_or_else(|| format!("`{arg}` requires a directory"))?;
                let path = PathBuf::from(value);
                if word == "root" {
                    root = Some(path);
                } else {
                    out = Some(path);
                }
                i += 2;
                continue;
            }
            _ => {}
        }

        if let Some(job) = command_for(word) {
            if command.is_some() {
                return Err(format!(
                    "unexpected argument `{arg}` (one command at a time)"
                ));
            }
            match job {
                Some(cmd) => command = Some(cmd),
                None => {
                    let joined = args[i + 1..].join(" ").trim().to_string();
                    command = Some(if word == "read" {
                        Command::Read(joined)
                    } else {
                        Command::Search(joined)
                    });
                    // `read` and `search` consume the rest of the line.
                    break;
                }
            }
            i += 1;
            continue;
        }

        if arg.starts_with('-') {
            return Err(format!("unknown option `{arg}`"));
        }
        return Err(format!("unknown command `{arg}`"));
    }

    if let Some(Command::Read(slug)) = &command {
        if slug.is_empty() {
            return Err("`read` needs a slug, e.g. `kc-docs read mcp`".into());
        }
    }
    if let Some(Command::Search(query)) = &command {
        if query.trim().is_empty() {
            return Err("`search` needs a query".into());
        }
    }

    let root = root.unwrap_or_else(default_root);
    let out = out.unwrap_or_else(|| root.join("docs/internal"));
    Ok(Some(Args {
        command: command.unwrap_or(Command::Check),
        root,
        out,
    }))
}

/// The checkout this binary was built from. `CARGO_MANIFEST_DIR` is baked in at
/// compile time (`crates/kc-docs`, two levels below the root), which is exactly
/// what an xtask-style tool wants; `--root` overrides it.
fn default_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .map(Path::to_path_buf)
        .unwrap_or_else(|| PathBuf::from("."))
}

fn compile(root: &Path) -> Result<Vec<ParsedDoc>, Vec<parse::DocError>> {
    let (mut docs, mut errors) = scan::collect(root);
    errors.extend(parse::validate_unique(&docs));
    if !errors.is_empty() {
        for error in &errors {
            eprintln!("error: {error}");
        }
        return Err(errors);
    }
    docs.sort_by(|a, b| a.slug.cmp(&b.slug));
    Ok(docs)
}

fn check(args: &Args) -> ExitCode {
    let docs = match compile(&args.root) {
        Ok(docs) => docs,
        Err(_) => return ExitCode::FAILURE,
    };

    let expected = render_files(&docs);
    let mut problems: Vec<String> = Vec::new();

    for (name, content) in &expected {
        let path = args.out.join(name);
        match fs::read_to_string(&path) {
            Ok(existing) if existing == *content => {}
            Ok(_) => problems.push(format!("{} is out of date", path.display())),
            Err(_) => problems.push(format!("{} is missing", path.display())),
        }
    }
    for stale in stale_files(&args.out, &expected) {
        problems.push(format!(
            "{} no longer corresponds to any @kc-doc block",
            stale.display()
        ));
    }

    if problems.is_empty() {
        println!(
            "ok: {} topic(s) documented, {} files up to date",
            docs.len(),
            expected.len()
        );
        quality_gate()
    } else {
        for problem in problems.iter().take(20) {
            eprintln!("stale: {problem}");
        }
        if problems.len() > 20 {
            eprintln!("... and {} more", problems.len() - 20);
        }
        eprintln!("\nRun `cargo run -p kc-docs -- --write` and commit docs/internal.");
        ExitCode::FAILURE
    }
}

fn write(args: &Args) -> ExitCode {
    let docs = match compile(&args.root) {
        Ok(docs) => docs,
        Err(_) => return ExitCode::FAILURE,
    };
    let expected = render_files(&docs);

    if let Err(e) = fs::create_dir_all(&args.out) {
        eprintln!("kc-docs: cannot create {}: {e}", args.out.display());
        return ExitCode::FAILURE;
    }

    let mut written = 0usize;
    for (name, content) in &expected {
        let path = args.out.join(name);
        let unchanged = fs::read_to_string(&path)
            .map(|existing| existing == *content)
            .unwrap_or(false);
        if unchanged {
            continue;
        }
        if let Err(e) = fs::write(&path, content) {
            eprintln!("kc-docs: cannot write {}: {e}", path.display());
            return ExitCode::FAILURE;
        }
        written += 1;
    }

    let mut removed = 0usize;
    for stale in stale_files(&args.out, &expected) {
        if let Err(e) = fs::remove_file(&stale) {
            eprintln!("kc-docs: cannot remove {}: {e}", stale.display());
            return ExitCode::FAILURE;
        }
        removed += 1;
    }

    println!(
        "wrote {} file(s), removed {removed} stale file(s): {} topic(s) in {}",
        written,
        docs.len(),
        args.out.display()
    );
    quality_gate()
}

fn quality_gate() -> ExitCode {
    let problems = kc_docs::quality_problems();
    if problems.is_empty() {
        ExitCode::SUCCESS
    } else {
        for problem in problems {
            eprintln!("quality: {problem}");
        }
        ExitCode::FAILURE
    }
}

/// Files under `out` that carry our generated header but are no longer produced
/// by any block. Anything without the header is left alone: `docs/internal/` may
/// legitimately hold hand-written notes.
fn stale_files(out: &Path, expected: &BTreeMap<String, String>) -> Vec<PathBuf> {
    let mut stale = Vec::new();
    let Ok(entries) = fs::read_dir(out) else {
        return stale;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if !path.is_file() {
            continue;
        }
        let name = entry.file_name().to_string_lossy().to_string();
        if expected.contains_key(&name) {
            continue;
        }
        let generated = fs::read_to_string(&path)
            .map(|text| text.starts_with(GENERATED_MARKER))
            .unwrap_or(false);
        if generated {
            stale.push(path);
        }
    }
    stale.sort();
    stale
}

fn render_files(docs: &[ParsedDoc]) -> BTreeMap<String, String> {
    let mut files = BTreeMap::new();
    for doc in docs {
        files.insert(format!("{}.md", doc.slug), render_doc_file(doc));
    }
    files.insert("README.md".into(), render_index(docs));
    files.insert("index.json".into(), render_json(docs));
    files
}

fn generated_header(source: &str) -> String {
    format!("{GENERATED_MARKER}; DO NOT EDIT.\n     The source of truth is {source}. -->\n")
}

fn render_doc_file(doc: &ParsedDoc) -> String {
    let mut out = generated_header(&format!("the `@kc-doc` block at `{}`", doc.location()));
    out.push_str(&format!("\n# {}\n\n> {}\n\n", doc.title, doc.summary));
    out.push_str(&format!("- **Slug:** `{}`\n", doc.slug));
    if !doc.tags.is_empty() {
        out.push_str(&format!("- **Tags:** {}\n", doc.tags.join(", ")));
    }
    if !doc.applies_to.is_empty() {
        out.push_str(&format!(
            "- **Applies to:** {}\n",
            doc.applies_to
                .iter()
                .map(|a| format!("`{a}`"))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    out.push_str(&format!("- **Source:** `{}`\n\n---\n\n", doc.location()));
    out.push_str(kc_docs::demote_headings(doc.body.trim_end()).trim_end());
    out.push('\n');
    out
}

fn render_index(docs: &[ParsedDoc]) -> String {
    let mut out = generated_header("the `@kc-doc` blocks in the source tree");
    out.push_str(
        "\n# karucode internal documentation\n\n\
         These files are generated from `@kc-doc` comments in the code. The agent reads the same\n\
         entries through the `karucode_docs` tool, compiled into the binary at build time.\n\n\
         Edit the code, not these files. Then run:\n\n\
         ```bash\n\
         cargo run -p kc-docs -- --write   # regenerate\n\
         cargo run -p kc-docs -- --check   # what CI runs\n\
         ```\n\n\
         | Topic | What it covers | Source |\n\
         | --- | --- | --- |\n",
    );
    for doc in docs {
        out.push_str(&format!(
            "| [`{}`]({}.md) | {} | `{}` |\n",
            doc.slug,
            doc.slug,
            doc.summary.replace('|', "\\|"),
            doc.location()
        ));
    }
    out.push_str(&format!("\n{} topic(s).\n", docs.len()));
    out
}

fn render_json(docs: &[ParsedDoc]) -> String {
    let entries: Vec<serde_json::Value> = docs
        .iter()
        .map(|doc| {
            serde_json::json!({
                "slug": doc.slug,
                "title": doc.title,
                "summary": doc.summary,
                "tags": doc.tags,
                "applies_to": doc.applies_to,
                "source": doc.location(),
                "path": format!("{}.md", doc.slug),
            })
        })
        .collect();
    let mut text = serde_json::to_string_pretty(&serde_json::json!({
        "generated_by": "cargo run -p kc-docs -- --write",
        "count": entries.len(),
        "topics": entries,
    }))
    .expect("serialising docs cannot fail");
    text.push('\n');
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn argument_parsing_handles_each_command() {
        let args = parse_args(["list".to_string()]).unwrap().unwrap();
        assert!(matches!(args.command, Command::List));

        let args = parse_args([
            "--root".to_string(),
            "/tmp/ws".to_string(),
            "read".to_string(),
            "mcp".to_string(),
        ])
        .unwrap()
        .unwrap();
        assert_eq!(args.root, PathBuf::from("/tmp/ws"));
        assert!(matches!(args.command, Command::Read(slug) if slug == "mcp"));

        let args = parse_args([
            "search".to_string(),
            "provider".to_string(),
            "profiles".to_string(),
        ])
        .unwrap()
        .unwrap();
        assert!(matches!(args.command, Command::Search(q) if q == "provider profiles"));

        // Default command is the CI gate.
        let args = parse_args(std::iter::empty::<String>()).unwrap().unwrap();
        assert!(matches!(args.command, Command::Check));

        assert!(parse_args(["read".to_string()]).is_err());
        assert!(parse_args(["--nope".to_string()]).is_err());
    }

    #[test]
    fn rendered_files_include_index_and_json() {
        let docs = vec![ParsedDoc {
            slug: "x".into(),
            title: "X".into(),
            summary: "S".into(),
            tags: vec!["t".into()],
            applies_to: vec![],
            body: "Body".into(),
            path: "a.rs".into(),
            line: 3,
        }];
        let files = render_files(&docs);
        assert!(files.contains_key("x.md"));
        assert!(files["README.md"].contains("[`x`](x.md)"));
        assert!(files["index.json"].contains("\"slug\": \"x\""));
        assert!(files["x.md"].starts_with(GENERATED_MARKER));
    }
}
