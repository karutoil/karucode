//! Build-time documentation compiler.
//!
//! Every `cargo build` re-reads the workspace sources, extracts the `@kc-doc`
//! blocks and writes a Rust table of them into `$OUT_DIR/generated_docs.rs`,
//! which `src/lib.rs` includes. Documentation is therefore **never** stale in the
//! binary: it is compiled from the same revision as the code that implements it.
//!
//! A malformed or duplicate block fails the build with a `path:line: message`
//! diagnostic, so the habit cannot silently decay. The human-readable copy under
//! `docs/internal/` is produced by `cargo run -p kc-docs -- --write` and checked
//! by `--check`.

#[path = "src/parse.rs"]
mod parse;
#[path = "src/scan.rs"]
mod scan;

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let root = workspace_root();
    println!("cargo:rerun-if-changed=build.rs");
    for dir in scan::SCAN_ROOTS {
        let path = root.join(dir);
        if path.is_dir() {
            // Watching the directory (not an enumerated file list) is what makes
            // a brand-new doc block take effect without touching build.rs.
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }

    let (docs, mut errors) = scan::collect(&root);
    if docs.is_empty() {
        panic!(
            "kc-docs: found no @kc-doc blocks under {}.\n\
             The documentation compiler is scanning the wrong tree, or the doc blocks were \
             deleted. See docs/INTERNAL-DOCS.md.",
            root.display()
        );
    }
    errors.extend(parse::validate_unique(&docs));
    if !errors.is_empty() {
        let rendered = errors
            .iter()
            .map(|e| format!("  {e}"))
            .collect::<Vec<_>>()
            .join("\n");
        panic!(
            "kc-docs: {} invalid documentation block(s):\n{rendered}\n\n\
             The format is documented in docs/INTERNAL-DOCS.md and summarised in AGENTS.md.",
            errors.len()
        );
    }

    let mut sorted = docs;
    sorted.sort_by(|a, b| a.slug.cmp(&b.slug).then_with(|| a.path.cmp(&b.path)));
    write_generated(&sorted);
}

/// The workspace root: `crates/kc-docs` -> `crates` -> root.
fn workspace_root() -> PathBuf {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    manifest
        .parent()
        .and_then(Path::parent)
        .map(Path::to_path_buf)
        .unwrap_or(manifest)
}

fn rust_literal(value: &str) -> String {
    // `Debug` for `str` is a valid Rust string literal: quotes and backslashes
    // are escaped, newlines become `\n`, and non-ASCII text is preserved.
    format!("{value:?}")
}

fn rust_str_slice(values: &[String]) -> String {
    let items = values
        .iter()
        .map(|v| rust_literal(v))
        .collect::<Vec<_>>()
        .join(", ");
    format!("&[{items}]")
}

fn write_generated(docs: &[parse::ParsedDoc]) {
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is set by cargo"));
    let mut code = String::new();
    code.push_str(
        "// @generated by crates/kc-docs/build.rs from @kc-doc comments in the workspace.\n\
         // Do not edit: run `cargo run -p kc-docs -- --write` for the human-readable copy.\n\n",
    );
    code.push_str("/// Every documentation entry, sorted by slug.\n");
    code.push_str("pub(crate) static GENERATED: &[RawDoc] = &[\n");
    let mut seen: BTreeSet<&str> = BTreeSet::new();
    for doc in docs {
        // Belt and braces: validate_unique already rejected duplicates.
        if !seen.insert(doc.slug.as_str()) {
            continue;
        }
        code.push_str("    RawDoc {\n");
        code.push_str(&format!("        slug: {},\n", rust_literal(&doc.slug)));
        code.push_str(&format!("        title: {},\n", rust_literal(&doc.title)));
        code.push_str(&format!(
            "        summary: {},\n",
            rust_literal(&doc.summary)
        ));
        code.push_str(&format!("        tags: {},\n", rust_str_slice(&doc.tags)));
        code.push_str(&format!(
            "        applies_to: {},\n",
            rust_str_slice(&doc.applies_to)
        ));
        code.push_str(&format!("        body: {},\n", rust_literal(&doc.body)));
        code.push_str(&format!(
            "        source: {},\n",
            rust_literal(&doc.location())
        ));
        code.push_str("    },\n");
    }
    code.push_str("];\n");

    let dest = out_dir.join("generated_docs.rs");
    fs::write(&dest, code)
        .unwrap_or_else(|e| panic!("kc-docs: cannot write {}: {e}", dest.display()));
}
